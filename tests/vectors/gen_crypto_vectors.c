/*
 * Generates tests/vectors/crypto_vectors.txt from the real libmhash and
 * libmcrypt, so that steghide's in-tree replacements can be checked against
 * the libraries that wrote steghide 0.5.1 files.
 *
 * It is not part of the build. To regenerate the vectors:
 *
 *   cc -o gen_crypto_vectors tests/vectors/gen_crypto_vectors.c -lmcrypt -lmhash
 *   ./gen_crypto_vectors > tests/vectors/crypto_vectors.txt
 *
 * Line formats (all binary values in lower-case hex, "-" for empty):
 *
 *   md5 <input> <digest>
 *   crc32 <input> <mhash output bytes>
 *   keygen <key size> <password> <key>           mhash KEYGEN_MCRYPT with MD5
 *   algorithm <name> <block size> <key size> <is block algorithm> <supported key sizes, comma-separated, or ->
 *   mode <name> <is block mode> <is block algorithm mode> <has iv>
 *   cipher <algorithm> <mode> <key> <iv> <plaintext> <ciphertext>
 */

#include <mcrypt.h>
#include <mhash.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static void hex(const unsigned char *p, size_t n)
{
	size_t i;
	if (n == 0) {
		fputs(" -", stdout);
		return;
	}
	putchar(' ');
	for (i = 0; i < n; i++)
		printf("%02x", p[i]);
}

static void pattern(unsigned char *p, size_t n, unsigned seed)
{
	size_t i;
	for (i = 0; i < n; i++)
		p[i] = (unsigned char) ((i * 37 + seed * 101 + 11) & 0xff);
}

static void hash_line(const char *name, hashid id, const unsigned char *in, size_t n)
{
	MHASH td = mhash_init(id);
	unsigned char out[64];
	mhash(td, in, n);
	mhash_deinit(td, out);
	fputs(name, stdout);
	hex(in, n);
	hex(out, mhash_get_block_size(id));
	putchar('\n');
}

static void keygen_line(unsigned keysize, const char *password)
{
	KEYGEN data;
	unsigned char key[512];
	memset(&data, 0, sizeof data);
	data.hash_algorithm[0] = MHASH_MD5;
	if (mhash_keygen_ext(KEYGEN_MCRYPT, data, key, keysize,
			(unsigned char *) password, strlen(password)) < 0) {
		fprintf(stderr, "keygen failed\n");
		exit(1);
	}
	printf("keygen %u", keysize);
	hex((const unsigned char *) password, strlen(password));
	hex(key, keysize);
	putchar('\n');
}

/* encrypt PTLEN bytes with KEYLEN bytes of key and print a cipher line */
static void cipher_line(const char *algo, const char *mode, int keylen, size_t ptlen, unsigned seed)
{
	MCRYPT td = mcrypt_module_open((char *) algo, NULL, (char *) mode, NULL);
	unsigned char key[512], iv[64], pt[512], buf[512];
	int ivlen = 0;

	if (td == MCRYPT_FAILED) {
		fprintf(stderr, "cannot open %s/%s\n", algo, mode);
		exit(1);
	}
	pattern(key, keylen, seed);
	pattern(pt, ptlen, seed + 1);
	if (mcrypt_enc_mode_has_iv(td)) {
		ivlen = mcrypt_enc_get_iv_size(td);
		pattern(iv, ivlen, seed + 2);
	}
	if (mcrypt_generic_init(td, key, keylen, mcrypt_enc_mode_has_iv(td) ? iv : NULL) < 0) {
		fprintf(stderr, "cannot init %s/%s with a %d byte key\n", algo, mode, keylen);
		exit(1);
	}
	memcpy(buf, pt, ptlen);
	mcrypt_generic(td, buf, ptlen);
	mcrypt_generic_deinit(td);
	mcrypt_module_close(td);

	printf("cipher %s %s", algo, mode);
	hex(key, keylen);
	hex(iv, ivlen);
	hex(pt, ptlen);
	hex(buf, ptlen);
	putchar('\n');
}

static const char *const algorithms[] = {
	"cast-128", "gost", "rijndael-128", "twofish", "arcfour", "cast-256",
	"loki97", "rijndael-192", "saferplus", "wake", "des", "rijndael-256",
	"serpent", "xtea", "blowfish", "enigma", "rc2", "tripledes", NULL
};

static const char *const modes[] = {
	"cbc", "cfb", "ctr", "ecb", "ncfb", "nofb", "ofb", "stream", NULL
};

int main(void)
{
	static const char *const strings[] = {
		"", "a", "abc", "message digest", "abcdefghijklmnopqrstuvwxyz",
		"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789",
		"12345678901234567890123456789012345678901234567890123456789012345678901234567890",
		"123456789", "steghide compat", NULL
	};
	static const char *const passwords[] = {
		"", "a", "steghide compat", "p\xc3\xa4ssw\xc3\xb6rd \xd0\xba\xd0\xbb\xd1\x8e\xd1\x87 \xf0\x9f\x94\x91",
		"long passphrase long passphrase long passphrase long passphrase long passphrase "
		"long passphrase long passphrase long passphrase long passphrase long passphrase",
		NULL
	};
	static const unsigned keysizes[] = { 1, 8, 13, 16, 17, 24, 32, 56, 128, 256 };
	unsigned char bytes[1000];
	int i, j;

	printf("# generated by tests/vectors/gen_crypto_vectors.c from libmcrypt %s and mhash %d\n",
		mcrypt_check_version(NULL), MHASH_API_VERSION);

	for (i = 0; strings[i] != NULL; i++)
		hash_line("md5", MHASH_MD5, (const unsigned char *) strings[i], strlen(strings[i]));
	pattern(bytes, sizeof bytes, 0);
	hash_line("md5", MHASH_MD5, bytes, sizeof bytes);

	for (i = 0; strings[i] != NULL; i++)
		hash_line("crc32", MHASH_CRC32, (const unsigned char *) strings[i], strlen(strings[i]));
	for (i = 0; i < 256; i++)
		bytes[i] = (unsigned char) i;
	hash_line("crc32", MHASH_CRC32, bytes, 256);
	pattern(bytes, sizeof bytes, 0);
	hash_line("crc32", MHASH_CRC32, bytes, sizeof bytes);

	for (i = 0; passwords[i] != NULL; i++)
		for (j = 0; j < (int) (sizeof keysizes / sizeof keysizes[0]); j++)
			keygen_line(keysizes[j], passwords[i]);

	for (i = 0; algorithms[i] != NULL; i++) {
		int nsizes = 0, k;
		int *sizes = mcrypt_module_get_algo_supported_key_sizes((char *) algorithms[i], NULL, &nsizes);
		printf("algorithm %s %d %d %d ", algorithms[i],
			mcrypt_module_get_algo_block_size((char *) algorithms[i], NULL),
			mcrypt_module_get_algo_key_size((char *) algorithms[i], NULL),
			mcrypt_module_is_block_algorithm((char *) algorithms[i], NULL));
		if (nsizes == 0)
			putchar('-');
		for (k = 0; k < nsizes; k++)
			printf(k ? ",%d" : "%d", sizes[k]);
		putchar('\n');
		mcrypt_free(sizes);
	}

	for (i = 0; modes[i] != NULL; i++) {
		MCRYPT td = mcrypt_module_open(strcmp(modes[i], "stream") ? "rijndael-128" : "arcfour", NULL, (char *) modes[i], NULL);
		printf("mode %s %d %d %d\n", modes[i],
			mcrypt_module_is_block_mode((char *) modes[i], NULL),
			mcrypt_module_is_block_algorithm_mode((char *) modes[i], NULL),
			mcrypt_enc_mode_has_iv(td));
		mcrypt_module_close(td);
	}

	/* every algorithm in every mode it supports, with the maximum key size
	 * (which is what steghide uses): 96 bytes (whole blocks for every block
	 * size) and, for modes that allow it, 37 bytes (a partial last block) */
	for (i = 0; algorithms[i] != NULL; i++) {
		int block = mcrypt_module_is_block_algorithm((char *) algorithms[i], NULL);
		int maxkey = mcrypt_module_get_algo_key_size((char *) algorithms[i], NULL);
		for (j = 0; modes[j] != NULL; j++) {
			if (mcrypt_module_is_block_algorithm_mode((char *) modes[j], NULL) != block)
				continue;
			cipher_line(algorithms[i], modes[j], maxkey, 96, i * 8 + j);
			if (strcmp(modes[j], "ecb") && strcmp(modes[j], "cbc"))
				cipher_line(algorithms[i], modes[j], maxkey, 37, i * 8 + j + 100);
		}
	}

	/* shorter keys, one block in ecb (16 bytes for stream algorithms), to
	 * cover the key schedules and libmcrypt's zero-extension of short keys:
	 * every length up to 32 bytes, then a sample */
	for (i = 0; algorithms[i] != NULL; i++) {
		static const int longer[] = { 40, 48, 55, 56, 64, 100, 127, 128, 200, 255, 256, 0 };
		int block = mcrypt_module_is_block_algorithm((char *) algorithms[i], NULL);
		int maxkey = mcrypt_module_get_algo_key_size((char *) algorithms[i], NULL);
		int bs = mcrypt_module_get_algo_block_size((char *) algorithms[i], NULL);
		int len, k;
		for (len = 1; len <= maxkey && len <= 32; len++)
			cipher_line(algorithms[i], block ? "ecb" : "stream", len, block ? bs : 16, 1000 + len);
		for (k = 0; longer[k] != 0; k++)
			if (longer[k] <= maxkey)
				cipher_line(algorithms[i], block ? "ecb" : "stream", longer[k], block ? bs : 16, 1000 + longer[k]);
	}

	return 0;
}
